// === Exécution ==============================================================
async function main() {
  const before = await prisma.exerciseLibrary.count()
  let created = 0
  let updated = 0

  for (const ex of EXERCISES) {
    const existing = await prisma.exerciseLibrary.findUnique({ where: { slug: ex.slug } })
    if (existing) {
      await prisma.exerciseLibrary.update({
        where: { slug: ex.slug },
        data: { ...ex, isActive: true, archivedAt: null },
      })
      updated++
    } else {
      await prisma.exerciseLibrary.create({ data: ex })
      created++
    }
  }

  const after = await prisma.exerciseLibrary.count()
  // eslint-disable-next-line no-console
  console.log(`[seed:exercise-library] avant=${before} après=${after} créés=${created} mis_à_jour=${updated}`)
}

main()
  .then(async () => { await prisma.$disconnect() })
  .catch(async (e) => {
    // eslint-disable-next-line no-console
    console.error('[seed:exercise-library] erreur :', e)
    await prisma.$disconnect()
    process.exit(1)
  })
